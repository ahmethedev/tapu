export const AUTO_START = '<!-- tapu:auto:start -->';
export const AUTO_END = '<!-- tapu:auto:end -->';
export const GENERATED_NOTE = 'Generated by tapu init. Edit explanations outside this block.';

export type PageState = 'active' | 'removed' | 'out_of_scope';

export const LIFECYCLE_WARNING: Record<Exclude<PageState, 'active'>, string> = {
  removed:
    '> **Removed:** this relation was not found in the database at the last `tapu init`. The description below is the last generated snapshot, not current metadata. Tapu keeps this page; delete it when it is no longer useful.',
  out_of_scope:
    '> **Out of scope:** this relation’s schema is not in the configured schemas, so Tapu no longer checks it. The description below is the last generated snapshot, not current metadata.',
};

const WHY_PLACEHOLDER = '_Not documented yet. What does this table represent, and why is it separate from related tables?_';
const TEMPLATE_TAIL = `\n## Why it exists\n\n${WHY_PLACEHOLDER}\n\n## Notes\n`;

