export const RULES_TEMPLATE = `# Project database conventions

Tapu creates this file once and never overwrites it. Record the conventions your team has actually agreed on; agents receive this file with \`tapu explain --rules\`.

An empty section means no convention was supplied. It does not mean that anything is allowed.

## Naming

## Migrations

## Data handling
`;

export interface IndexEntry {
  id: string;
  schema: string;
  name: string;
  kind?: RelationKind;
  purpose?: string;
  state: PageState;
}

export function renderIndex(entries: IndexEntry[]): string {
  const link = (e: IndexEntry) => `[${mdInline(e.id)}](tables/${encodeURIComponent(pageFileName(e.schema, e.name))})`;
  const active = entries.filter((e) => e.state === 'active');
  const archived = entries.filter((e) => e.state !== 'active');
  const out = [
    '# Database wiki',
    '',
    'Generated by `tapu init`; do not edit this file. Set a purpose in each page’s frontmatter.',
    '',
    '## Relations',
    '',
  ];
  if (active.length === 0) out.push('_No relations in the configured schemas._');
  for (const e of active) {
    out.push(`- ${link(e)} (${KIND_LABEL[e.kind!]}) — ${e.purpose ? mdInline(e.purpose) : '_undocumented_'}`);
  }
  if (archived.length > 0) {
    out.push('', '## Archived pages', '');
    for (const e of archived) {
      out.push(`- ${link(e)} — ${e.state === 'removed' ? 'removed from the database' : 'outside the configured schemas'}`);
    }
  }
  return out.join('\n') + '\n';
}
