import { mkdir, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { parseDocument, type Document } from 'yaml';
import type { Catalog, Column, Relation, RelationKind } from './catalog.js';
import { compareStrings } from './catalog.js';
import { projectPaths, readTextIfExists, writeIfChanged, type Config } from './project.js';
import { stripControlChars } from './sanitize.js';
