// Frontmatter

const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

type FrontParse = { ok: true; front: Frontmatter } | { ok: false; reason: string };

/**
 * Validates recognized frontmatter fields. `tapu` must be 1 and `table` the
 * page's canonical ID. purpose/owner are strings, tags a list of strings,
 * columns a mapping of mappings with a string `note` and a boolean
 * `sensitive`. Absent or null fields count as empty. Unknown keys are allowed
 * (and preserved, since Tapu never rewrites frontmatter) but not exposed.
 */
export function readFrontmatter(value: unknown, id: string): FrontParse {
  const fail = (reason: string): FrontParse => ({ ok: false, reason });
  if (!isRecord(value)) return fail('frontmatter is not a mapping');
  if (value.tapu !== 1) return fail('frontmatter "tapu" must be 1');
  if (value.table !== id) return fail(`frontmatter "table" must be ${JSON.stringify(id)}`);
  const text = (key: string): string | null => {
    const v = value[key];
    return v === undefined || v === null ? '' : typeof v === 'string' ? v : null;
  };
  const purpose = text('purpose');
  if (purpose === null) return fail('"purpose" must be a string');
  const owner = text('owner');
  if (owner === null) return fail('"owner" must be a string');
  let tags: string[] = [];
  if (value.tags !== undefined && value.tags !== null) {
    if (!Array.isArray(value.tags) || !value.tags.every((t) => typeof t === 'string')) {
      return fail('"tags" must be a list of strings');
    }
    tags = value.tags as string[];
  }
  const columns = new Map<string, ColumnOverride>();
  if (value.columns !== undefined && value.columns !== null) {
    if (!isRecord(value.columns)) return fail('"columns" must be a mapping');
    for (const [name, raw] of Object.entries(value.columns)) {
      const override: ColumnOverride = {};
      if (raw !== null) {
        if (!isRecord(raw)) return fail(`"columns.${name}" must be a mapping`);
        if (raw.note !== undefined && raw.note !== null) {
          if (typeof raw.note !== 'string') return fail(`"columns.${name}.note" must be a string`);
          override.note = raw.note;
        }
        if (raw.sensitive !== undefined && raw.sensitive !== null) {
          if (typeof raw.sensitive !== 'boolean') return fail(`"columns.${name}.sensitive" must be true or false`);
          override.sensitive = raw.sensitive;
        }
      }
      columns.set(name, override);
    }
  }
  return { ok: true, front: { purpose, owner, tags, columns } };
}

/** Effective sensitivity: a frontmatter override (true or false) wins over name-based detection. */
export function isSensitive(col: Column, front: Frontmatter | null): boolean {
  return front?.columns.get(col.name)?.sensitive ?? col.sensitive;
}

// ---------------------------------------------------------------------------
// Parsing

export interface ParsedPage {
  text: string;
  front: Frontmatter;
  state: PageState;
  hash: string;
  docHash: string;
  /** Offset just after the start-marker line. */
  autoStart: number;
  /** Offset of the end-marker line. */
  autoEnd: number;
  /** Offset (within text) of the auto-block body after the header and any lifecycle warning. */
  bodyStart: number;
  /** Human-written Markdown outside the frontmatter and the generated block. */
  before: string;
  after: string;
}

export type PageParse = { ok: true; page: ParsedPage } | { ok: false; reason: string };

interface Line {
  start: number;
  end: number; // exclusive, before the newline
  next: number; // start of the next line (text.length at EOF)
  text: string; // without a trailing \r
}

function lines(text: string, from = 0): Line[] {
  const out: Line[] = [];
  let pos = from;
  while (pos < text.length) {
    const nl = text.indexOf('\n', pos);
    const end = nl === -1 ? text.length : nl;
    out.push({ start: pos, end, next: nl === -1 ? text.length : nl + 1, text: text.slice(pos, end).replace(/\r$/, '') });
    pos = nl === -1 ? text.length : nl + 1;
  }
  return out;
}

const STATE_RE = /^<!-- tapu:state (active|removed|out_of_scope) -->$/;
const HASH_RE = /^<!-- tapu:hash ([0-9a-f]{64}) -->$/;
const DOC_HASH_RE = /^<!-- tapu:doc-hash ([0-9a-f]{64}) -->$/;

/** Parses and validates a page for relation `id`. Never modifies anything. */
export function parsePage(text: string, id: string): PageParse {
  const fail = (reason: string): PageParse => ({ ok: false, reason });
  const all = lines(text);
  if (all[0]?.text !== '---') return fail('missing frontmatter');
  const close = all.findIndex((l, i) => i > 0 && l.text === '---');
  if (close === -1) return fail('unterminated frontmatter');

  const yaml = text.slice(all[0].next, all[close]!.start);
  const doc = parseDocument(yaml, { uniqueKeys: true, prettyErrors: false });
  if (doc.errors.length > 0) {
    const dup = doc.errors.some((e) => /unique|duplicate/i.test(e.message));
    return fail(dup ? 'frontmatter has duplicate keys' : 'frontmatter is not valid YAML');
  }
  let value: unknown;
  try {
    value = doc.toJS({ maxAliasCount: 50 });
  } catch (err) {
    return fail(`frontmatter cannot be read (${errorMessage(err)})`);
  }
  const front = readFrontmatter(value, id);
  if (!front.ok) return front;

  const body = all.slice(close + 1);
  const starts = body.filter((l) => l.text === AUTO_START);
  const ends = body.filter((l) => l.text === AUTO_END);
  if (starts.length !== 1 || ends.length !== 1) return fail('tapu:auto markers are missing or duplicated');
  const s = starts[0]!;
  const e = ends[0]!;
  if (e.start < s.next) return fail('tapu:auto markers are out of order');

  const block = lines(text.slice(s.next, e.start));
  const state = STATE_RE.exec(block[0]?.text ?? '');
  const hash = HASH_RE.exec(block[1]?.text ?? '');
  const docHash = DOC_HASH_RE.exec(block[2]?.text ?? '');
  if (!state || !hash || !docHash) return fail('the generated block header (state, hash, doc-hash) is malformed');
  let bodyStart = s.next + (block[3]?.start ?? text.slice(s.next, e.start).length);
  const warning = block[3]?.text;
  if (warning !== undefined && Object.values(LIFECYCLE_WARNING).includes(warning)) {
    bodyStart = s.next + (block[4]?.text === '' ? block[4].next : block[3]!.next);
  }

  return {
    ok: true,
    page: {
      text,
      front: front.front,
      state: state[1] as PageState,
      hash: hash[1]!,
      docHash: docHash[1]!,
      autoStart: s.next,
      autoEnd: e.start,
      bodyStart,
      before: text.slice(all[close]!.next, s.start),
      after: text.slice(e.next),
    },
  };
}

/** Human notes for explain: text outside frontmatter and block, minus Tapu's own untouched template. */
export function humanNotes(page: ParsedPage, id: string): string {
  let before = page.before.replace(/\r\n?/g, '\n').trim();
  const title = `# ${mdInline(id)}`;
  if (before === title || before.startsWith(title + '\n')) before = before.slice(title.length).trim();
  const after = page.after
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .filter((l) => l !== WHY_PLACEHOLDER)
    .join('\n')
    .trim();
  const headingsOnly = after.replace(/^## (Why it exists|Notes)$/gm, '').trim() === '';
  return [before, headingsOnly ? '' : after].filter(Boolean).join('\n\n');
}

