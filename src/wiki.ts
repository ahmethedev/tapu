// Rendering

export interface RenderContext {
  enums: Map<string, EnumType>;
  captured: Map<string, Relation>;
}

export function renderContext(catalog: Catalog): RenderContext {
  return {
    enums: new Map(catalog.enums.map((e) => [e.id, e])),
    captured: new Map(catalog.relations.map((r) => [r.id, r])),
  };
}

function pageLink(id: string, ctx: RenderContext, prefix = ''): string {
  const rel = ctx.captured.get(id);
  if (!rel) return `${mdInline(id)} (not captured)`;
  return `[${mdInline(id)}](${prefix}${encodeURIComponent(pageFileName(rel.schema, rel.name))})`;
}

const KIND_LABEL: Record<RelationKind, string> = {
  table: 'table',
  partitioned_table: 'partitioned table',
  view: 'view',
  materialized_view: 'materialized view',
};

function columnFlags(rel: Relation, col: Column, front: Frontmatter | null): string[] {
  const flags: string[] = [];
  if (rel.primaryKey?.columns.includes(col.name)) flags.push('PK');
  if (rel.foreignKeys.some((fk) => fk.columns.includes(col.name))) flags.push('FK');
  if (rel.uniques.some((u) => u.columns.length === 1 && u.columns[0] === col.name)) flags.push('UNIQUE');
  if (col.identity === 'always') flags.push('IDENTITY ALWAYS');
  if (col.identity === 'by_default') flags.push('IDENTITY BY DEFAULT');
  if (col.generated !== null) flags.push('GENERATED');
  if (isSensitive(col, front)) flags.push('SENSITIVE');
  return flags;
}

function fkText(fk: ForeignKey, ctx: RenderContext): string {
  const parts = [
    `${mdInline(fk.name)}: (${mdInline(fk.columns.join(', '))}) → ${pageLink(fk.ref, ctx)} (${mdInline(fk.refColumns.join(', '))})`,
    `on delete ${fk.onDelete}`,
    `on update ${fk.onUpdate}`,
  ];
  if (fk.match !== 'simple') parts.push(`match ${fk.match}`);
  if (fk.deferrable) parts.push(fk.initiallyDeferred ? 'deferrable, initially deferred' : 'deferrable');
  if (!fk.validated) parts.push('not validated');
  return parts.join('; ');
}

export function warningText(w: Warning): string {
  switch (w.code) {
    case 'fk_without_index':
      return `fk_without_index: ${w.columns.join(', ')}`;
    case 'stale_note':
      return `stale_note: ${w.column}`;
    default:
      return w.code;
  }
}

/** Generated content after the header lines: everything a human reviewer sees in the block. */
export function renderBody(rel: Relation, front: Frontmatter | null, ctx: RenderContext): string {
  const out: string[] = [GENERATED_NOTE, ''];
  out.push(`**Kind:** ${KIND_LABEL[rel.kind]} · **Estimated rows:** ${rel.rows === null ? 'unknown' : String(rel.rows)}`, '');
  if (rel.comment) out.push(`**Comment:** ${mdInline(rel.comment)}`, '');

  out.push('### Columns', '', '| Column | Type | Nullable | Default | Flags | Comment |', '| --- | --- | --- | --- | --- | --- |');
  for (const col of rel.columns) {
    const def = col.generated !== null ? `generated: ${col.generated}` : (col.default ?? '');
    const cells = [col.name, col.type, col.nullable ? 'yes' : 'no', def, columnFlags(rel, col, front).join(', '), col.comment ?? ''];
    out.push(`| ${cells.map(mdInline).join(' | ')} |`);
  }
  out.push('');

  const enumIds = [...new Set(rel.columns.map((c) => c.enumType).filter((e): e is string => e !== null))].sort(compareStrings);
  if (enumIds.length > 0) {
    out.push('### Enum values', '');
    for (const id of enumIds) {
      const e = ctx.enums.get(id);
      const values = e ? e.values.map(mdInline).join(', ') : '_unknown_';
      out.push(`- ${mdInline(id)}${e?.external ? ' (outside the configured schemas)' : ''}: ${values}`);
    }
    out.push('');
  }

  const section = (title: string, items: string[]) => {
    if (items.length === 0) return;
    out.push(`### ${title}`, '', ...items.map((i) => `- ${i}`), '');
  };
  section('Primary key', rel.primaryKey ? [`${mdInline(rel.primaryKey.name)}: ${mdInline(rel.primaryKey.definition)}`] : []);
  section('Unique constraints', rel.uniques.map((u) => `${mdInline(u.name)}: ${mdInline(u.definition)}`));
  section('Check constraints', rel.checks.map((c) => `${mdInline(c.name)}: ${mdInline(c.definition)}`));
  section('Foreign keys', rel.foreignKeys.map((fk) => fkText(fk, ctx)));
  section(
    'Referenced by',
    rel.referencedBy.map((r) => `${pageLink(r.from, ctx)} (${mdInline(r.columns.join(', '))}) — ${mdInline(r.name)}`),
  );
  section(
    'Indexes',
    rel.indexes.map((ix) => {
      const notes = [ix.valid ? '' : ' (invalid)', ix.constraint ? ` (implements ${mdInline(ix.constraint)})` : ''].join('');
      return `${mdInline(ix.name)}: ${mdInline(ix.definition)}${notes}`;
    }),
  );
  if (rel.viewDefinition !== null) out.push('### View definition', '', mdCodeBlock(rel.viewDefinition), '');
  if (rel.partitionKey !== null) out.push(`**Partition key:** ${mdInline(rel.partitionKey)}`, '');
  section('Warnings', relationWarnings(rel, front).map((w) => mdInline(warningText(w))));

  return out.join('\n');
}

function header(state: PageState, hash: string, docHash: string): string {
  return `<!-- tapu:state ${state} -->\n<!-- tapu:hash ${hash} -->\n<!-- tapu:doc-hash ${docHash} -->\n`;
}

/** Content between the markers for a live relation. */
export function renderAuto(rel: Relation, front: Frontmatter | null, ctx: RenderContext): string {
  return header('active', rel.hash, rel.docHash) + renderBody(rel, front, ctx);
}

function yamlString(s: string): string {
  return /^[a-z_][a-z0-9_.]*$/.test(s) ? s : JSON.stringify(s);
}

export function renderNewPage(rel: Relation, ctx: RenderContext): string {
  return [
    '---',
    'tapu: 1',
    `table: ${yamlString(rel.id)}`,
    'purpose: ""',
    'owner: ""',
    'tags: []',
    'columns: {}',
    '---',
    '',
    `# ${mdInline(rel.id)}`,
    '',
    AUTO_START,
    renderAuto(rel, null, ctx) + AUTO_END,
    TEMPLATE_TAIL,
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Merging: only the bytes between the markers ever change.

export type PageUpdate = { ok: true; text: string } | { ok: false; reason: string };

function replaceAuto(page: ParsedPage, auto: string): string {
  return page.text.slice(0, page.autoStart) + auto + page.text.slice(page.autoEnd);
}

/** Regenerates the block of an existing page for a live relation (reactivating archived pages). */
export function updatePage(text: string, rel: Relation, ctx: RenderContext): PageUpdate {
  const parsed = parsePage(text, rel.id);
  if (!parsed.ok) return parsed;
  return { ok: true, text: replaceAuto(parsed.page, renderAuto(rel, parsed.page.front, ctx)) };
}

/** Archives a page: new state and warning; the last generated description is kept as it is. */
export function archivePage(text: string, id: string, state: Exclude<PageState, 'active'>): PageUpdate {
  const parsed = parsePage(text, id);
  if (!parsed.ok) return parsed;
  const page = parsed.page;
  const body = text.slice(page.bodyStart, page.autoEnd);
  const auto = header(state, page.hash, page.docHash) + LIFECYCLE_WARNING[state] + '\n\n' + body;
  return { ok: true, text: replaceAuto(page, auto) };
}

